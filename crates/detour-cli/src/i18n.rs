pub fn t() -> &'static T {
    static LANG: OnceLock<bool> = OnceLock::new();
    let ru = *LANG.get_or_init(|| {
        let env = ["DETOUR_LANG", "LC_ALL", "LC_MESSAGES", "LANG"].iter().find_map(|k| std::env::var(k).ok().filter(|v| !v.is_empty()));
        env.or_else(sys_locale::get_locale).is_some_and(|l| l.to_lowercase().starts_with("ru"))
    });
    if ru { &RU } else { &EN }
}

/// A core error as a sentence.
pub fn error_text(e: &serde_json::Value) -> String {
    let ru = std::ptr::eq(t(), &RU);
    let kind = e["kind"].as_str().unwrap_or("");
    let s = |en: &str, ru_: &str| if ru { ru_.to_string() } else { en.to_string() };
    match kind {
        "locked" => s("The vault is locked", "Хранилище заблокировано"),
        "wrongMasterPassword" => s("Wrong master password", "Неверный мастер-пароль"),
        "notInitialized" => s("There is no vault yet", "Хранилища ещё нет"),
        "notFound" => format!("{}: {}", s("Not found", "Не найдено"), e["what"].as_str().unwrap_or("")),
        "unreachable" => format!("{} {}", s("Can't reach", "Не удаётся подключиться к"), e["endpoint"].as_str().unwrap_or("")),
        "authFailed" => t().permission_denied.to_string(),
        "agentUnavailable" => s("ssh-agent is not running", "ssh-agent не запущен"),
        "forbidden" => s("Your access in the team doesn't allow this", "Ваш доступ в команде этого не позволяет"),
        "denied" => t().denied.to_string(),
        "timedOut" => t().timed_out.to_string(),
        "disconnected" => t().core_unreachable.to_string(),
        _ => e["message"].as_str().map(str::to_string).unwrap_or_else(|| if kind.is_empty() { e.to_string() } else { kind.to_string() }),
    }
}
